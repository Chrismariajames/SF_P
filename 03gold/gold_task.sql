--Load Dim_Country
CREATE OR REPLACE TASK ECOM_DW.GOLD.LOAD_DIM_COUNTRY_TASK
WAREHOUSE = ECOM_WH
SCHEDULE = '5 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA('ECOM_DW.SILVER.CUSTOMERS_STREAM')
AS
MERGE INTO ECOM_DW.GOLD.DIM_COUNTRY T
USING
(
    SELECT DISTINCT
        COUNTRY_CODE,
        COUNTRY_NAME
    FROM ECOM_DW.SILVER.CUSTOMERS_STREAM
    WHERE METADATA$ACTION = 'INSERT'
) S
ON T.COUNTRY_CODE = S.COUNTRY_CODE
WHEN NOT MATCHED THEN
INSERT
(
    COUNTRY_CODE,
    COUNTRY_NAME
)
VALUES
(
    S.COUNTRY_CODE,
    S.COUNTRY_NAME
);

