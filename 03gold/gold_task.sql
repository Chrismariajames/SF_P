CREATE OR REPLACE VIEW ECOM_DW.GOLD.VW_INVENTORY_HEALTH
AS

SELECT

    P.PRODUCT_NAME,

    SUM(F.ON_HAND_QTY) AS STOCK_QTY,

    SUM(F.RESERVED_QTY) AS RESERVED_QTY,

    SUM(F.AVAILABLE_QTY) AS AVAILABLE_QTY,

    CASE
        WHEN SUM(F.AVAILABLE_QTY) < 10
            THEN 'LOW STOCK'

        WHEN SUM(F.AVAILABLE_QTY) = 0
            THEN 'OUT OF STOCK'

        ELSE 'HEALTHY'
    END AS STOCK_STATUS

FROM ECOM_DW.GOLD.FACT_INVENTORY F

JOIN ECOM_DW.GOLD.DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY

GROUP BY P.PRODUCT_NAME;

