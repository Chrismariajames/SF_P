    --. FACT_INVENTORY Load Task
    CREATE OR REPLACE TASK ECOM_DW.GOLD.LOAD_FACT_INVENTORY_TASK
WAREHOUSE = ECOM_WH

AFTER ECOM_DW.GOLD.LOAD_DIM_PRODUCT_TASK

WHEN SYSTEM$STREAM_HAS_DATA('ECOM_DW.SILVER.INVENTORY_STREAM')

AS

INSERT INTO ECOM_DW.GOLD.FACT_INVENTORY
(
    SNAPSHOT_DATE_KEY,
    PRODUCT_KEY,
    ON_HAND_QTY,
    RESERVED_QTY,
    AVAILABLE_QTY,
    UNIT_COST,
    INVENTORY_VALUE
)

SELECT

    TO_NUMBER(
        TO_CHAR(
            TO_DATE(SNAPSHOT_DATE),
            'YYYYMMDD'
        )
    ) AS SNAPSHOT_DATE_KEY,

    DP.PRODUCT_KEY,

    TRY_TO_NUMBER(I.ON_HAND_QTY,18,2),

    TRY_TO_NUMBER(I.RESERVED_QTY,18,2),

    TRY_TO_NUMBER(I.AVAILABLE_QTY,18,2),

    TRY_TO_NUMBER(I.UNIT_COST,18,2),

    TRY_TO_NUMBER(I.INVENTORY_VALUE,18,2)

FROM ECOM_DW.SILVER.INVENTORY_STREAM I

INNER JOIN ECOM_DW.GOLD.DIM_PRODUCT DP
    ON I.PRODUCT_ID = DP.PRODUCT_ID

WHERE
    TRY_TO_NUMBER(I.ON_HAND_QTY) IS NOT NULL
    AND TRY_TO_NUMBER(I.UNIT_COST) IS NOT NULL;

    CREATE OR REPLACE VIEW ECOM_DW.GOLD.VW_INVENTORY_DEDUP
AS

SELECT *
FROM
(
    SELECT
        *,
        ROW_NUMBER() OVER
        (
            PARTITION BY SNAPSHOT_DATE, PRODUCT_ID
            ORDER BY UPDATED_TIMESTAMP DESC
        ) AS RN

    FROM ECOM_DW.SILVER.INVENTORY_SILVER
)
WHERE RN = 1;

CREATE OR REPLACE TABLE ECOM_DW.GOLD.AGG_INVENTORY_DAILY
(
    SNAPSHOT_DATE_KEY     NUMBER,
    TOTAL_ON_HAND_QTY     NUMBER(18,2),
    TOTAL_RESERVED_QTY    NUMBER(18,2),
    TOTAL_AVAILABLE_QTY   NUMBER(18,2),
    TOTAL_INVENTORY_VALUE NUMBER(18,2)
);

CREATE OR REPLACE TASK ECOM_DW.GOLD.LOAD_AGG_INVENTORY_TASK
WAREHOUSE = ECOM_WH

AFTER ECOM_DW.GOLD.LOAD_FACT_INVENTORY_TASK

AS

MERGE INTO ECOM_DW.GOLD.AGG_INVENTORY_DAILY T

USING
(
    SELECT
        SNAPSHOT_DATE_KEY,

        SUM(ON_HAND_QTY)       AS TOTAL_ON_HAND_QTY,

        SUM(RESERVED_QTY)      AS TOTAL_RESERVED_QTY,

        SUM(AVAILABLE_QTY)     AS TOTAL_AVAILABLE_QTY,

        SUM(INVENTORY_VALUE)   AS TOTAL_INVENTORY_VALUE

    FROM ECOM_DW.GOLD.FACT_INVENTORY

    GROUP BY SNAPSHOT_DATE_KEY

) S

ON T.SNAPSHOT_DATE_KEY = S.SNAPSHOT_DATE_KEY

WHEN MATCHED THEN UPDATE SET

    T.TOTAL_ON_HAND_QTY = S.TOTAL_ON_HAND_QTY,
    T.TOTAL_RESERVED_QTY = S.TOTAL_RESERVED_QTY,
    T.TOTAL_AVAILABLE_QTY = S.TOTAL_AVAILABLE_QTY,
    T.TOTAL_INVENTORY_VALUE = S.TOTAL_INVENTORY_VALUE

WHEN NOT MATCHED THEN

INSERT
(
    SNAPSHOT_DATE_KEY,
    TOTAL_ON_HAND_QTY,
    TOTAL_RESERVED_QTY,
    TOTAL_AVAILABLE_QTY,
    TOTAL_INVENTORY_VALUE
)

VALUES
(
    S.SNAPSHOT_DATE_KEY,
    S.TOTAL_ON_HAND_QTY,
    S.TOTAL_RESERVED_QTY,
    S.TOTAL_AVAILABLE_QTY,
    S.TOTAL_INVENTORY_VALUE
);

CREATE MATERIALIZED VIEW ECOM_DW.GOLD.MV_PRODUCT_INVENTORY
AS

SELECT

    D.YEAR_NUMBER,
    D.MONTH_NUMBER,

    P.PRODUCT_NAME,
    P.BRAND,

    SUM(F.ON_HAND_QTY) AS TOTAL_STOCK,

    SUM(F.INVENTORY_VALUE) AS TOTAL_VALUE

FROM ECOM_DW.GOLD.FACT_INVENTORY F

JOIN ECOM_DW.GOLD.DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY

JOIN ECOM_DW.GOLD.DIM_DATE D
    ON F.SNAPSHOT_DATE_KEY = D.DATE_KEY

GROUP BY
    D.YEAR_NUMBER,
    D.MONTH_NUMBER,
    P.PRODUCT_NAME,
    P.BRAND;

