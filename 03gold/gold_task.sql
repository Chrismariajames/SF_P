--Load dim_customer SCD Type 2
CREATE OR REPLACE TASK ECOM_DW.GOLD.LOAD_DIM_CUSTOMER_TASK
WAREHOUSE = ECOM_WH
AFTER ECOM_DW.GOLD.LOAD_DIM_GEOGRAPHY_TASK
AS
MERGE INTO ECOM_DW.GOLD.DIM_CUSTOMER T
USING
(
    SELECT
        CUSTOMER_ID,
        CUSTOMER_ID AS CUSTOMER_NK,
        FIRST_NAME,
        LAST_NAME,
        CONCAT(FIRST_NAME,' ',LAST_NAME) AS FULL_NAME,
        EMAIL,
        PHONE,
        GENDER,
        DATE_OF_BIRTH,
        CUSTOMER_STATUS,
        G.GEOGRAPHY_KEY,
        CURRENT_TIMESTAMP() AS EFFECTIVE_FROM
    FROM ECOM_DW.SILVER.CUSTOMERS_STREAM S
    LEFT JOIN ECOM_DW.GOLD.DIM_GEOGRAPHY G
        ON S.CITY = G.CITY
        AND S.POSTAL_CODE = G.POSTAL_CODE
) SRC
ON T.CUSTOMER_ID = SRC.CUSTOMER_ID
AND T.IS_CURRENT = TRUE
WHEN MATCHED AND
(
    T.EMAIL <> SRC.EMAIL
    OR T.PHONE <> SRC.PHONE
    OR T.CUSTOMER_STATUS <> SRC.CUSTOMER_STATUS
    OR T.GEOGRAPHY_KEY <> SRC.GEOGRAPHY_KEY
)
THEN UPDATE SET
T.EFFECTIVE_TO = CURRENT_TIMESTAMP(),
    T.IS_CURRENT = FALSE
WHEN NOT MATCHED THEN
INSERT
(
    CUSTOMER_ID,
    CUSTOMER_NK,
    FIRST_NAME,
    LAST_NAME,
    FULL_NAME,
    EMAIL,
    PHONE,
    GENDER,
    DATE_OF_BIRTH,
    CUSTOMER_STATUS,
    GEOGRAPHY_KEY,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT
)
VALUES
(
    SRC.CUSTOMER_ID,
    SRC.CUSTOMER_NK,
    SRC.FIRST_NAME,
    SRC.LAST_NAME,
    SRC.FULL_NAME,
    SRC.EMAIL,
    SRC.PHONE,
    SRC.GENDER,
    SRC.DATE_OF_BIRTH,
    SRC.CUSTOMER_STATUS,
    SRC.GEOGRAPHY_KEY,
    CURRENT_TIMESTAMP(),
    NULL,
    TRUE
);

