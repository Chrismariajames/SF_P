CREATE OR REPLACE TASK ECOM_DW.GOLD.LOAD_FACT_SALES_TASK
WAREHOUSE = ECOM_WH
AFTER ECOM_DW.GOLD.LOAD_DIM_CUSTOMER_TASK,
      ECOM_DW.GOLD.LOAD_DIM_PRODUCT_TASK,
      ECOM_DW.GOLD.LOAD_DIM_CHANNEL_TASK,
      ECOM_DW.GOLD.LOAD_DIM_PROMOTION_TASK
AS
INSERT INTO ECOM_DW.GOLD.FACT_SALES
(
    ORDER_ID,
    ORDER_LINE_NK,
    ORDER_DATE_KEY,
    CUSTOMER_KEY,
    PRODUCT_KEY,
    CHANNEL_KEY,
    PROMOTION_KEY,
    QUANTITY,
    UNIT_PRICE,
    UNIT_COST,
    GROSS_AMOUNT,
    DISCOUNT_AMOUNT,
    TAX_AMOUNT,
    NET_AMOUNT
)
SELECT
    O.ORDER_ID,
    O.ORDER_LINE_ID,
    TO_NUMBER(TO_CHAR(TO_DATE(O.ORDER_DATE),'YYYYMMDD')),
    DC.CUSTOMER_KEY,
    DP.PRODUCT_KEY,
    DCH.CHANNEL_KEY,
    PR.PROMOTION_KEY,
    O.QUANTITY::NUMBER(18,2),
    O.UNIT_PRICE::NUMBER(18,2),
    DP.UNIT_COST,
    O.GROSS_AMOUNT::NUMBER(18,2),
    O.DISCOUNT_AMOUNT::NUMBER(18,2),
    O.TAX_AMOUNT::NUMBER(18,2),
    O.NET_AMOUNT::NUMBER(18,2)
FROM ECOM_DW.SILVER.ORDERS_STREAM O
LEFT JOIN ECOM_DW.GOLD.DIM_CUSTOMER DC
    ON O.CUSTOMER_ID = DC.CUSTOMER_ID
    AND DC.IS_CURRENT = TRUE
LEFT JOIN ECOM_DW.GOLD.DIM_PRODUCT DP
    ON O.PRODUCT_ID = DP.PRODUCT_ID
LEFT JOIN ECOM_DW.GOLD.DIM_CHANNEL DCH
    ON O.CHANNEL_CODE = DCH.CHANNEL_CODE
LEFT JOIN ECOM_DW.GOLD.DIM_PROMOTION PR
    ON O.PROMO_CODE = PR.PROMO_CODE;

