
# PART 1 — ROW LEVEL SECURITY (RLS)

RLS in Snowflake is implemented using:

* **Row Access Policies**
* (Optionally) Secure Views

---

# 1. CUSTOMER COUNTRY-BASED RLS


Restrict users so they only see customers from their region (example: Germany users see only Germany data).

---

## Step 1: Create Row Access Policy

```sql
CREATE OR REPLACE ROW ACCESS POLICY ECOM_DW.GOLD.RAP_CUSTOMER_COUNTRY
AS (COUNTRY_NAME STRING)
RETURNS BOOLEAN ->

CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'SYSADMIN') THEN TRUE

    WHEN CURRENT_ROLE() = 'ECOM_ANALYST_ROLE'
         AND COUNTRY_NAME = 'Germany'
    THEN TRUE

    WHEN CURRENT_ROLE() = 'ECOM_BI_ROLE'
    THEN TRUE

    ELSE FALSE
END;
```

---

## Step 2: Apply to DIM_CUSTOMER

```sql
ALTER TABLE ECOM_DW.GOLD.DIM_CUSTOMER
ADD ROW ACCESS POLICY ECOM_DW.GOLD.RAP_CUSTOMER_COUNTRY
ON (COUNTRY_NAME);
```

---

# 2. FACT SALES ROW LEVEL SECURITY

## Goal

Filter FACT_SALES via CUSTOMER → COUNTRY mapping.

---

## Create Policy

```sql
CREATE OR REPLACE ROW ACCESS POLICY ECOM_DW.GOLD.RAP_FACT_SALES
AS (CUSTOMER_KEY NUMBER)
RETURNS BOOLEAN ->

EXISTS
(
    SELECT 1
    FROM ECOM_DW.GOLD.DIM_CUSTOMER C
    WHERE C.CUSTOMER_KEY = CUSTOMER_KEY
    AND (
        CURRENT_ROLE() IN ('ACCOUNTADMIN','SYSADMIN')
        OR C.COUNTRY_NAME = 'Germany'
        OR CURRENT_ROLE() = 'ECOM_BI_ROLE'
    )
);
```

---

##  Apply Policy

```sql
ALTER TABLE ECOM_DW.GOLD.FACT_SALES
ADD ROW ACCESS POLICY ECOM_DW.GOLD.RAP_FACT_SALES
ON (CUSTOMER_KEY);
```

---

# 3. CUSTOMER REVIEW RLS (Sensitive Data)


Restrict review visibility (especially negative feedback)

---

##  Policy

```sql
CREATE OR REPLACE ROW ACCESS POLICY ECOM_DW.GOLD.RAP_CUSTOMER_REVIEW
AS (SENTIMENT_LABEL STRING)
RETURNS BOOLEAN ->

CASE
    WHEN CURRENT_ROLE() = 'ACCOUNTADMIN' THEN TRUE

    WHEN CURRENT_ROLE() = 'ECOM_ANALYST_ROLE'
         AND SENTIMENT_LABEL != 'NEGATIVE'
    THEN TRUE

    WHEN CURRENT_ROLE() = 'ECOM_BI_ROLE' THEN TRUE

    ELSE FALSE
END;
```

---

## Step 2: Apply

```sql
ALTER TABLE ECOM_DW.GOLD.FACT_CUSTOMER_REVIEW
ADD ROW ACCESS POLICY ECOM_DW.GOLD.RAP_CUSTOMER_REVIEW
ON (SENTIMENT_LABEL);
```

---

# 4. PRODUCT-BASED RLS (Optional Advanced)

Example: restrict inactive products

```sql
CREATE OR REPLACE ROW ACCESS POLICY ECOM_DW.GOLD.RAP_PRODUCT
AS (IS_ACTIVE BOOLEAN)
RETURNS BOOLEAN ->

CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','SYSADMIN') THEN TRUE
    WHEN IS_ACTIVE = TRUE THEN TRUE
    ELSE FALSE
END;
```

---



```sql
ALTER TABLE ECOM_DW.GOLD.DIM_PRODUCT
ADD ROW ACCESS POLICY ECOM_DW.GOLD.RAP_PRODUCT
ON (IS_ACTIVE);
```

