# — SECURE DATA SHARING

Snowflake supports secure sharing via **Secure Data Shares (zero-copy sharing)**.

---

# 1. CREATE SHARE OBJECT

## Create Share

```sql
CREATE OR REPLACE SHARE ECOM_ANALYTICS_SHARE;
```

---

# 2. GRANT DATABASE ACCESS

```sql
GRANT USAGE ON DATABASE ECOM_DW TO SHARE ECOM_ANALYTICS_SHARE;

GRANT USAGE ON SCHEMA ECOM_DW.GOLD TO SHARE ECOM_ANALYTICS_SHARE;
```

---

# 3. GRANT OBJECTS TO SHARE

## FACT TABLES

```sql
GRANT SELECT ON TABLE ECOM_DW.GOLD.FACT_SALES TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.FACT_SHIPMENT TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.FACT_INVENTORY TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.FACT_CUSTOMER_REVIEW TO SHARE ECOM_ANALYTICS_SHARE;
```

---

## DIMENSIONS

```sql
GRANT SELECT ON TABLE ECOM_DW.GOLD.DIM_CUSTOMER TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.DIM_PRODUCT TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.DIM_DATE TO SHARE ECOM_ANALYTICS_SHARE;

GRANT SELECT ON TABLE ECOM_DW.GOLD.DIM_GEOGRAPHY TO SHARE ECOM_ANALYTICS_SHARE;
```

---

## AGGREGATES

```sql
GRANT SELECT ON TABLE ECOM_DW.GOLD.AGG_DAILY_SALES TO SHARE ECOM_ANALYTICS_SHARE;
```

---

# 4. ADD CONSUMER ACCOUNT


```sql
ALTER SHARE ECOM_ANALYTICS_SHARE
