# 5. OPTIONAL: CREATE SECURE VIEWS FOR SHARING

Instead of raw tables 

## Secure Sales View

```sql
CREATE OR REPLACE SECURE VIEW ECOM_DW.GOLD.VW_SHARED_SALES
AS
SELECT
    F.ORDER_DATE_KEY,
    F.CUSTOMER_KEY,
    F.PRODUCT_KEY,
    F.NET_AMOUNT
FROM ECOM_DW.GOLD.FACT_SALES F;
```

---

## Share Secure View

```sql
GRANT SELECT ON VIEW ECOM_DW.GOLD.VW_SHARED_SALES TO SHARE ECOM_ANALYTICS_SHARE;
```

